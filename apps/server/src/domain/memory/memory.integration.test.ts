import assert from "node:assert/strict";
import test from "node:test";
import {randomUUID} from "node:crypto";
import {Kysely,PostgresDialect,sql} from "kysely";
import {Pool} from "pg";
import type {DB} from "../../infrastructure/database/schema.js";
import {runMigrations} from "../../infrastructure/database/database.js";
import {MemoryService} from "./memory-service.js";
const url=process.env.TEST_DATABASE_URL;
const integration=url?test:test.skip;
integration("Memory PostgreSQL: Fanto isolation, correction, search and capacity without kinds",async()=>{
 if(!/test/i.test(new URL(url!).pathname))throw Error("Dedicated test database required");
 const admin=new Kysely<DB>({dialect:new PostgresDialect({pool:new Pool({connectionString:url})})});
 const name=`memory_test_${randomUUID().replaceAll("-","")}`;
 await sql.raw(`CREATE DATABASE ${name}`).execute(admin);
 const connection=new URL(url!);connection.pathname=`/${name}`;
 const db=new Kysely<DB>({dialect:new PostgresDialect({pool:new Pool({connectionString:connection.href})})});
 let embeddingCalls=0;const vector=Array.from({length:768},(_,i)=>i===0?1:0);
 const service=MemoryService.create(db,{async embed(){embeddingCalls++;return vector;}});
 try{
  await runMigrations(db);
  const role=randomUUID(),other=randomUUID();
  assert.deepEqual(await service.list(role),[]);
  const memory=await service.create(role,{content:"我认识霄汉，他希望我记住他的名字。"});
  assert.equal((await service.list(role)).length,1);
  assert.equal((await service.list(other)).length,0);
  assert.equal((await service.update(other,memory.memoryId,{content:"越权"})),undefined);
  assert.equal(await service.remove(other,memory.memoryId),false);
  const updated=await service.update(role,memory.memoryId,{content:"我认识霄汉，我们现在是朋友。"});
  assert.equal(updated?.memoryId,memory.memoryId);
  assert.match(updated!.content,/朋友/);
  const found=await service.search(role,"霄汉");
  assert.equal(found.length,1);assert.equal(found[0]!.fantoId,role);
  assert.deepEqual(await service.search(other,"霄汉"),[]);
  const before=embeddingCalls;await service.list(role);assert.equal(embeddingCalls,before);
  while((await service.list(role)).length<49)await service.create(role,{content:"我还记得："+randomUUID()});
  const concurrent=await Promise.allSettled([service.create(role,{content:"第一项"}),service.create(role,{content:"第二项"})]);
  assert.equal(concurrent.filter(result=>result.status==="fulfilled").length,1);
  assert.equal((await service.list(role)).length,50);
  await assert.rejects(service.create(role,{content:"超过上限"}),/capacity/);
  await service.update(role,memory.memoryId,{content:"我现在仍然认识霄汉。"});
  assert.equal(await service.remove(role,memory.memoryId),true);
 }finally{await db.destroy();await sql.raw(`DROP DATABASE ${name} WITH (FORCE)`).execute(admin);await admin.destroy();}
});
